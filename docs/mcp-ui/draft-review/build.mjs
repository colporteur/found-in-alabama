// Builds the review panel into one self-contained HTML string:
//   docs/mcp-ui/draft-review/{index.src.html, app.src.mjs}
//     -> lib/mcp/ui/draft-review-html.ts
// The script is bundled with the MCP Apps SDK and inlined, because the panel's
// sandbox only runs inline scripts unless other origins are allowed.
// Run from the repo root (see README.md in this folder for the one-time setup):
//   node docs/mcp-ui/draft-review/build.mjs
import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "..", "..", "lib", "mcp", "ui", "draft-review-html.ts");

const result = await build({
  entryPoints: [join(here, "app.src.mjs")],
  bundle: true,
  format: "iife",
  minify: true,
  target: "es2020",
  write: false,
  legalComments: "none",
});
// "</script" inside the bundle would end the inline script early.
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const template = await readFile(join(here, "index.src.html"), "utf8");
if (!template.includes("/*__APP_JS__*/")) throw new Error("index.src.html lost its /*__APP_JS__*/ marker");
const html = template.replace("/*__APP_JS__*/", () => js);

await mkdir(dirname(out), { recursive: true });
await writeFile(
  out,
  "// GENERATED by docs/mcp-ui/draft-review/build.mjs. Do not edit by hand:\n" +
    "// change index.src.html or app.src.mjs there and rebuild.\n" +
    "// The review panel's page (an MCP App), served by lib/mcp/review-panel-tools.ts.\n" +
    "/* eslint-disable */\n" +
    "export const DRAFT_REVIEW_HTML: string = " + JSON.stringify(html) + ";\n"
);
console.log(`wrote ${out} (${(html.length / 1024).toFixed(0)} KB)`);
